-- Schema for the python-standards reference agent (Postgres).
--
-- AUTHOR  Craig Hunt
--
-- Safe to run at any time. CREATE TABLE IF NOT EXISTS leaves an existing
-- table alone, which means it also leaves a MISSING COLUMN alone, so the
-- generated ALTER block below adds whatever an older database lacks and the
-- gate at the end refuses to exit zero on a schema the agent cannot use.
--
-- Every free-text column takes type text rather than a bounded varchar. A
-- varchar(n) holding a message or a version string eventually aborts a run
-- mid-pipeline, and Postgres charges nothing extra for text.
--
-- See standard 8 in the README.

-- One row per package per day. A measurement, never revised except by a
-- second reading on the same day, which replaces it.
CREATE TABLE IF NOT EXISTS observations (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                text NOT NULL,
    pinned_version      text NOT NULL,
    latest_version      text NOT NULL DEFAULT '',
    latest_released_on  date,
    observed_on         date NOT NULL,
    error               text NOT NULL DEFAULT '',
    UNIQUE (name, observed_on)
);

-- One row per distinct problem, carrying its own lifecycle. first_seen lets a
-- digest separate a new problem from one already accepted, which is what stops
-- every run re-announcing the same list.
CREATE TABLE IF NOT EXISTS findings (
    finding_id      text PRIMARY KEY,
    finding_type    text NOT NULL,
    severity        text NOT NULL,
    subject         text NOT NULL,
    message         text NOT NULL DEFAULT '',
    detail          text NOT NULL DEFAULT '',
    recommendation  text NOT NULL DEFAULT '',
    first_seen      date NOT NULL,
    last_seen       date NOT NULL,
    resolved_at     date,
    occurrences     integer NOT NULL DEFAULT 1
);

-- One row per run, written at the start and updated at the end, so a run that
-- crashes partway still exists. count_runs is the agent's only notion of its
-- own history; writing it last would let a late crash erase the run entirely.
CREATE TABLE IF NOT EXISTS run_log (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_date            timestamptz NOT NULL,
    packages_checked    integer NOT NULL DEFAULT 0,
    findings_total      integer NOT NULL DEFAULT 0,
    findings_new        integer NOT NULL DEFAULT 0,
    findings_resolved   integer NOT NULL DEFAULT 0,
    duration_seconds    integer NOT NULL DEFAULT 0,
    status              text NOT NULL DEFAULT '',
    error_log           text NOT NULL DEFAULT '',
    notes               text NOT NULL DEFAULT ''
);

