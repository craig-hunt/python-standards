CREATE INDEX IF NOT EXISTS ix_observations_name_date
    ON observations (name, observed_on DESC);
CREATE INDEX IF NOT EXISTS ix_findings_open ON findings (resolved_at, severity);
CREATE INDEX IF NOT EXISTS ix_run_log_date ON run_log (run_date DESC);

-- BEGIN GENERATED GATE
DO $$
DECLARE
    gap text;
BEGIN
    SELECT string_agg(r.t || '.' || r.c, ', ' ORDER BY r.t, r.c)
      INTO gap
      FROM (VALUES
        ('findings', 'detail'),
        ('findings', 'finding_id'),
        ('findings', 'finding_type'),
        ('findings', 'first_seen'),
        ('findings', 'last_seen'),
        ('findings', 'message'),
        ('findings', 'occurrences'),
        ('findings', 'recommendation'),
        ('findings', 'resolved_at'),
        ('findings', 'severity'),
        ('findings', 'subject'),
        ('observations', 'error'),
        ('observations', 'latest_released_on'),
        ('observations', 'latest_version'),
        ('observations', 'name'),
        ('observations', 'observed_on'),
        ('observations', 'pinned_version'),
        ('run_log', 'duration_seconds'),
        ('run_log', 'error_log'),
        ('run_log', 'findings_new'),
        ('run_log', 'findings_resolved'),
        ('run_log', 'findings_total'),
        ('run_log', 'notes'),
        ('run_log', 'packages_checked'),
        ('run_log', 'run_date'),
        ('run_log', 'status')
      ) AS r(t, c)
     WHERE NOT EXISTS (
         SELECT 1 FROM information_schema.columns ic
          WHERE ic.table_schema = current_schema()
            AND ic.table_name = r.t
            AND ic.column_name = r.c
     );

    IF gap IS NOT NULL THEN
        RAISE EXCEPTION 'Schema still incomplete after this script: % Those columns are NOT NULL without a default, so Postgres will not add them to a populated table. Recreate the affected table, or add each column with an explicit default and then drop the default.', gap;
    END IF;

    RAISE NOTICE 'Schema complete: every column the agent requires is present.';
END $$;
-- END GENERATED GATE
